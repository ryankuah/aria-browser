import AppKit
import WebKit

@main
struct DownloadsSmoke {
    @MainActor static func main() {
        NSApplication.shared.setActivationPolicy(.prohibited)
        Task { @MainActor in
            do {
                try await DownloadChecks().run()
                print("PASS: all download checks")
                exit(0)
            } catch {
                print("FAIL: \(error)")
                exit(1)
            }
        }
        NSApplication.shared.run()
    }
}

@MainActor
private final class DownloadChecks: NSObject, WKUIDelegate, WKDownloadDelegate {
    private var tabs: [BrowserTab] = []
    private var downloads: [WKDownload] = []
    private var destinations: [ObjectIdentifier: URL] = [:]
    private var completed: [Data] = []
    private var downloadError: Error?
    private let baseURL = URL(string: ProcessInfo.processInfo.environment["DOWNLOAD_FIXTURE_URL"]!)!
    private let directory = URL(fileURLWithPath: ProcessInfo.processInfo.environment["DOWNLOAD_FIXTURE_DIRECTORY"]!)

    struct Failure: Error, CustomStringConvertible {
        let description: String
    }

    private func require(_ condition: Bool, _ message: String) throws {
        if !condition { throw Failure(description: message) }
    }

    private func waitFor(_ message: String, _ predicate: () -> Bool) async throws {
        let deadline = Date().addingTimeInterval(12)
        while !predicate() {
            if let downloadError { throw downloadError }
            guard Date() < deadline else { throw Failure(description: "Timeout: \(message)") }
            try await Task.sleep(for: .milliseconds(50))
        }
    }

    private func makeTab(configuration: WKWebViewConfiguration? = nil) -> BrowserTab {
        let configuration = configuration ?? BrowserWebView.makeConfiguration()
        if tabs.isEmpty { configuration.websiteDataStore = .nonPersistent() }
        let tab = BrowserTab(webView: BrowserWebView(frame: .zero, configuration: configuration))
        tab.attachUIDelegate(self)
        tab.onDownloadDidBegin = { [weak self] _, download, _ in
            self?.downloads.append(download)
            download.delegate = self
        }
        tabs.append(tab)
        return tab
    }

    private func loadFixture(_ tab: BrowserTab) async throws {
        tab.load(baseURL.appendingPathComponent("page"))
        try await waitFor("fixture page") { tab.webView.title == "Download fixture" && !tab.webView.isLoading }
    }

    private func expectDownload(_ label: String, bytes: String = "download fixture bytes", action: () async throws -> Void) async throws {
        let previous = completed.count
        try await action()
        try await waitFor(label) { self.completed.count == previous + 1 }
        try require(completed.last == Data(bytes.utf8), "Incorrect downloaded bytes: \(label)")
        print("PASS: \(label)")
        fflush(nil)
    }

    func run() async throws {
        let tab = makeTab()
        let window = NSWindow(contentRect: NSRect(x: 0, y: 0, width: 800, height: 600),
                              styleMask: [.titled], backing: .buffered, defer: false)
        window.contentView = tab.webView
        defer { window.contentView = nil }
        // Exercise production navigation delegates with a real WebKit instance.
        for path in ["attachment", "pdf", "binary", "redirect"] {
            try await expectDownload(path) { tab.load(baseURL.appendingPathComponent(path)) }
        }
        try await loadFixture(tab)
        // A missing desktop UA used to restart this navigation, losing `download`.
        tab.webView.customUserAgent = "DownloadCompatibilityTest"
        try await expectDownload("download attribute survives UA mismatch") {
            _ = try await tab.webView.evaluateJavaScript("const a = document.createElement('a'); a.href = '/inline'; a.download = 'explicit.txt'; document.body.append(a); a.click(); true")
        }
        tab.webView.customUserAgent = BrowserWebView.desktopSafariUserAgent

        for scheme in ["blob", "data"] {
            try await loadFixture(tab)
            try await expectDownload("\(scheme) generated download", bytes: "generated bytes") {
                let href = scheme == "blob"
                    ? "URL.createObjectURL(new Blob(['generated bytes'], {type: 'text/plain'}))"
                    : "'data:text/plain,generated%20bytes'"
                _ = try await tab.webView.evaluateJavaScript("{ const a = document.createElement('a'); a.href = \(href); a.download = 'generated.txt'; document.body.append(a); a.click(); } true")
            }
        }

        try await loadFixture(tab)
        try await expectDownload("blob navigation without download attribute", bytes: "generated bytes") {
            _ = try await tab.webView.evaluateJavaScript("const frame = document.createElement('iframe'); document.body.append(frame); frame.src = URL.createObjectURL(new Blob(['generated bytes'], {type: 'application/octet-stream'})); true")
        }
        try await loadFixture(tab)
        try await expectDownload("temporary popup followed by redirected download") {
            _ = try await tab.webView.evaluateJavaScript("window.downloadPopup = window.open('about:blank'); if (!window.downloadPopup) throw new Error('Popup blocked'); setTimeout(() => window.downloadPopup.location = '/redirect', 100); true")
        }
        try await loadFixture(tab)
        try await expectDownload("POST form download preserves request body", bytes: "token=fixture-token") {
            _ = try await tab.webView.evaluateJavaScript("const form = document.createElement('form'); form.method = 'POST'; form.action = '/post'; form.innerHTML = '<input name=token value=fixture-token>'; document.body.append(form); form.submit(); true")
        }

        let count = completed.count
        tab.load(baseURL.appendingPathComponent("inline"))
        try await waitFor("inline content") { tab.webView.url?.path == "/inline" && !tab.webView.isLoading }
        let body = try await tab.webView.evaluateJavaScript("document.body.innerText") as? String
        try require(body == "download fixture bytes" && completed.count == count, "Inline content downloaded unexpectedly")
        print("PASS: inline text stays in the browser")
        tab.load(baseURL.appendingPathComponent("error"))
        try await waitFor("HTTP verification page") { tab.webView.title == "Verification required" && !tab.webView.isLoading }
        try require(tab.pageFailure == nil && completed.count == count, "HTTP verification page was blocked")
        print("PASS: renderable HTTP 403 verification page")

        try await loadFixture(tab)
        let frameReady = try await tab.webView.callAsyncJavaScript("""
            return await new Promise(resolve => {
                const frame = document.createElement('iframe');
                frame.onload = () => resolve(frame.contentDocument.body.textContent);
                setTimeout(() => resolve('Frame load timed out: ' + frame.contentDocument.body.textContent), 3000);
                frame.srcdoc = '<p>Frame ready</p>';
                document.body.append(frame);
            });
            """, arguments: [:], in: nil, contentWorld: .page) as? String
        try require(frameReady == "Frame ready", "srcdoc frame blocked: \(frameReady ?? "no result")")
        print("PASS: srcdoc frames")

        for address in ["file:///tmp/aria-test.txt", "javascript:alert(1)", "about:config", "unknown-app:test"] {
            try require(!BrowserNavigation.isAllowedWebContentURL(URL(string: address)!), "Unexpected allowed scheme: \(address)")
        }
        tab.webView.load(URLRequest(url: URL(string: "unknown-app:fixture")!))
        try await waitFor("visible unsupported navigation failure") { tab.pageFailure != nil }
        print("PASS: unsupported navigation stays blocked and reports a failure")
    }

    func webView(_ webView: WKWebView, createWebViewWith configuration: WKWebViewConfiguration,
                 for navigationAction: WKNavigationAction, windowFeatures: WKWindowFeatures) -> WKWebView? {
        makeTab(configuration: configuration).webView
    }

    func download(_ download: WKDownload, decideDestinationUsing response: URLResponse,
                  suggestedFilename: String, completionHandler: @escaping @MainActor @Sendable (URL?) -> Void) {
        let destination = directory.appendingPathComponent(UUID().uuidString)
        destinations[ObjectIdentifier(download)] = destination
        completionHandler(destination)
    }

    func downloadDidFinish(_ download: WKDownload) {
        do {
            completed.append(try Data(contentsOf: destinations[ObjectIdentifier(download)]!))
        } catch { downloadError = error }
    }

    func download(_ download: WKDownload, didFailWithError error: Error, resumeData: Data?) {
        downloadError = error
    }
}
